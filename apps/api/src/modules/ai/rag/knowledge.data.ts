/**
 * 内置命理知识片段（RAG 语料）。
 *
 * 这是一份结构化、可检索的命理规则库，覆盖十神含义、五行生克、
 * 旺衰格局、大运流年口诀、合冲刑害破、神煞解读等。
 * 检索时按盘面特征（tags）加权召回，交给 LLM 作为"讲解依据"，降低幻觉。
 *
 * 说明：内容为传统命理常见口径，仅供文化娱乐参考。
 */

export type KnowledgeTagWeight = number;

export interface KnowledgeChunk {
  id: string;
  topic: string;
  /**
   * 召回标签：十神名、五行、旺衰、维度关键字等。
   * 标签可附加权重（数字越大越强），格式："标签名" 或 "标签名:权重"。
   * 默认权重为 1。
   */
  tags: string[];
  content: string;
}

/** 解析带权重的标签 */
export function parseTags(tags: string[]): Array<{ tag: string; weight: number }> {
  return tags.map((t) => {
    const idx = t.indexOf(':');
    if (idx < 0) return { tag: t, weight: 1 };
    const w = Number(t.slice(idx + 1));
    return { tag: t.slice(0, idx), weight: Number.isFinite(w) ? w : 1 };
  });
}

